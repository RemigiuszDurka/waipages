#!/usr/bin/env python3
"""Build the standalone, inspectable Project 02 browser snapshot from source files."""
import csv
import json
import math
import random
import statistics
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "projects/02-earthquake-atlas"
SOURCE = BASE / "data/earthquakes.csv"
LAND = BASE / "data/ne_110m_land.geojson"
TARGET = BASE / "data/quake-data.js"


def great_circle_km(a, b):
    lat_a, lon_a, lat_b, lon_b = map(math.radians, (a[3], a[4], b[3], b[4]))
    h = math.sin((lat_b - lat_a) / 2) ** 2 + math.cos(lat_a) * math.cos(lat_b) * math.sin((lon_b - lon_a) / 2) ** 2
    return 12742 * math.asin(min(1, math.sqrt(h)))


def distance_bands(sequence):
    edges = (500, 2000, 5000, 10000, 15000)
    distances = [great_circle_km(a, b) for a, b in zip(sequence, sequence[1:])]
    counts = [0] * 6
    for distance in distances:
        counts[next((i for i, edge in enumerate(edges) if distance < edge), 5)] += 1
    return distances, counts


def relay_analysis(rows):
    """Compare chronological daily representatives with 200 within-year location permutations."""
    result = {}
    for threshold in (6.0, 6.5, 7.0):
        qualifying = [row for row in rows if row[5] >= threshold]
        strongest = {}
        for row in qualifying:
            day = tuple(row[:3])
            if day not in strongest or row[5] > strongest[day][5]:
                strongest[day] = row
        sequence = [strongest[day] for day in sorted(strongest)]
        observed_distances, observed_counts = distance_bands(sequence)
        year_indices = defaultdict(list)
        for index, row in enumerate(sequence):
            year_indices[row[0]].append(index)
        rng = random.Random(20261018 + round(threshold * 10))
        null_counts = []
        null_medians = []
        for _ in range(200):
            shuffled = sequence.copy()
            for indices in year_indices.values():
                locations = [shuffled[i] for i in indices]
                rng.shuffle(locations)
                for i, location in zip(indices, locations):
                    shuffled[i] = location
            distances, counts = distance_bands(shuffled)
            null_counts.append(counts)
            null_medians.append(statistics.median(distances))
        result[str(threshold)] = {
            "threshold": threshold,
            "records": len(qualifying),
            "days": len(sequence),
            "sameDayExtra": len(qualifying) - len(sequence),
            "pairs": len(observed_distances),
            "observedCounts": observed_counts,
            "nullMeanCounts": [round(statistics.mean(sample[i] for sample in null_counts), 1) for i in range(6)],
            "nullP05Counts": [sorted(sample[i] for sample in null_counts)[9] for i in range(6)],
            "nullP95Counts": [sorted(sample[i] for sample in null_counts)[189] for i in range(6)],
            "observedMedianKm": round(statistics.median(observed_distances)),
            "nullMeanMedianKm": round(statistics.mean(null_medians)),
            "permutations": 200,
        }
    return result


def main():
    rows = []
    raw_samples = []
    mixed_dates = 0
    with SOURCE.open(encoding="utf-8-sig", newline="") as stream:
        for source_row, item in enumerate(csv.DictReader(stream), 2):
            if source_row in (2, 3, 3380, 7514, 20652):
                raw_samples.append([source_row, item["Date"], item["Latitude"], item["Longitude"], item["Magnitude"]])
            raw_date = item["Date"]
            if "T" in raw_date:
                date = datetime.fromisoformat(raw_date.replace("Z", "+00:00"))
                mixed_dates += 1
            else:
                date = datetime.strptime(raw_date, "%m/%d/%Y")
            lat, lon, magnitude = (float(item[key]) for key in ("Latitude", "Longitude", "Magnitude"))
            if not (-90 <= lat <= 90 and -180 <= lon <= 180 and magnitude > 0):
                raise ValueError(f"Invalid values in source row {source_row}")
            rows.append([date.year, date.month, date.day, lat, lon, magnitude, source_row])
    if len(rows) != 23412 or mixed_dates != 3:
        raise ValueError(f"Unexpected source shape: {len(rows)} rows, {mixed_dates} ISO dates")
    land = json.loads(LAND.read_text(encoding="utf-8"))
    if land.get("type") != "FeatureCollection":
        raise ValueError("Natural Earth land must be GeoJSON FeatureCollection")
    payload = {"events": rows, "land": land, "rawSamples": raw_samples, "sourceRows": len(rows), "normalizedIsoDates": mixed_dates, "relay": relay_analysis(rows)}
    output = "// Generated by tools/build_quake_data.py from the cited CSV and Natural Earth GeoJSON.\nwindow.QUAKE_DATA = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"
    if "--check" in __import__("sys").argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            raise SystemExit("Project 02 browser snapshot is stale; run python tools/build_quake_data.py")
        print("Project 02 browser snapshot is current.")
    else:
        TARGET.write_text(output, encoding="utf-8")
        print(f"Built {len(rows):,} events and {len(land['features'])} land features: {TARGET}")


if __name__ == "__main__":
    main()
