"""Build the standalone Lab 01 browser bundle from its committed source CSV."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "projects/01-exoplanet-atlas/data/exoplanets.csv"
OUTPUT = ROOT / "projects/01-exoplanet-atlas/data/exoplanets-data.js"
JUPITER_RADIUS_EARTH = 11.21
JUPITER_MASS_EARTH = 317.83


def quantity(row: dict[str, str], field: str, unit: str, factor: float) -> float | None:
    raw = row[field]
    if not raw:
        return None
    value = float(raw)
    if value <= 0:
        return None
    if row[unit] == "Earth":
        return value
    if row[unit] == "Jupiter":
        return round(value * factor, 6)
    return None


def build() -> str:
    with SOURCE.open(encoding="utf-8-sig", newline="") as handle:
        source = list(csv.DictReader(handle))
    rows = []
    for item in source:
        year = int(item["discovery_year"])
        if not 1992 <= year <= 2023:
            raise ValueError(f"Unexpected discovery year for {item['name']}: {year}")
        rows.append([
            item["name"], year, item["planet_type"], item["detection_method"],
            quantity(item, "radius_multiplier", "radius_wrt", JUPITER_RADIUS_EARTH),
            quantity(item, "mass_multiplier", "mass_wrt", JUPITER_MASS_EARTH),
            item["radius_multiplier"], item["radius_wrt"],
        ])
    if len(rows) != 5250:
        raise ValueError(f"Expected 5,250 source records, found {len(rows)}")
    payload = {"columns": ["name", "year", "type", "method", "radius_earth", "mass_earth", "source_radius", "source_radius_unit"], "rows": rows}
    return "// Generated by tools/build_exoplanet_data.py from data/exoplanets.csv.\nwindow.EXOPLANET_ARCHIVE=" + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the committed bundle matches the CSV")
    args = parser.parse_args()
    content = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Project 01 browser bundle is stale; run python tools/build_exoplanet_data.py")
        print("Project 01 browser bundle matches 5,250 CSV records.")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")
